// ---- Pairing a phone -------------------------------------------------------------
//
// The phone app signs in with a device key: an API key of kind 'device'
// that it gets by exchanging a one-time pairing code. The trader makes the
// code in Settings ("Phone app"), where it shows as a QR of
// tj://pair?server=...&code=XXXX-XXXX and as text; the phone posts the code
// to /api/v1/pair (the one unauthenticated API route, throttled per
// address) and gets the key, the server's facts and the user back. A code
// lives pairDeadline, works once, and a new one retires the old. Device
// keys may do what agent keys may not: edit and delete journal entries,
// change settings, register for push. requireDeviceKey gates those.

const (
	pairDeadline = 5 * time.Minute
	pairAlphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789" // no 0/O/1/I
)

// newPairCode mints a code like "AB7Q-K2MN".
func newPairCode() (string, error) {
	b := make([]byte, 8)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	var sb strings.Builder
	for i, c := range b {
		if i == 4 {
			sb.WriteByte('-')
		}
		sb.WriteByte(pairAlphabet[int(c)%len(pairAlphabet)])
	}
	return sb.String(), nil
}

// normalizePairCode reads a code as typed: case, spaces and the dash do
// not matter.
func normalizePairCode(s string) string {
	s = strings.ToUpper(strings.TrimSpace(s))
	s = strings.NewReplacer("-", "", " ", "", "O", "0", "I", "1").Replace(s)
	if len(s) != 8 {
		return ""
	}
	for _, c := range s {
		if !strings.ContainsRune(pairAlphabet, c) && c != '0' && c != '1' {
			return ""
		}
	}
	return s[:4] + "-" + s[4:]
}

// pairView is the Settings card's state after "Pair a phone".
type pairView struct {
	Code    string
	URL     string
	QR      template.HTML
	Expires time.Time
	Server  string
}

// pairServerURL is the origin the phone should talk to: the configured
// external URL, else the one this request arrived on.
func (h *Handlers) pairServerURL(r *http.Request) string {
	if u := strings.TrimRight(strings.TrimSpace(h.ExternalURL), "/"); u != "" {
		return u
	}
	return requestBaseURL(r)
}

// pairURL is what the QR holds.
func pairURL(server, code string) string {
	return "tj://pair?server=" + server + "&code=" + code
}

// SettingsPairStart: POST /settings/devices/pair - make a pairing code and
// show it (QR + text) on the settings page.
func (h *Handlers) SettingsPairStart(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	uid := userID(ctx)
	code, err := newPairCode()
	if err != nil {
		h.serverError(w, fmt.Errorf("pair code: %w", err))
		return
	}
	_ = h.Queries.ExpirePairCodesForUser(ctx, uid)
	_ = h.Queries.DeleteOldPairCodes(ctx, time.Now().UTC().Add(-24*time.Hour))
	expires := time.Now().UTC().Add(pairDeadline)
	if _, err := h.Queries.CreatePairCode(ctx, models.CreatePairCodeParams{UserID: uid, CodeSha256: auth.HashAPIKey(code), DeviceHint: "", ExpiresAt: expires}); err != nil {
		h.serverError(w, fmt.Errorf("create pair code: %w", err))
		return
	}
	server := h.pairServerURL(r)
	v := &pairView{Code: code, URL: pairURL(server, code), Expires: expires, Server: server}
	if m, err := qr.Encode(v.URL); err == nil {
		v.QR = template.HTML(m.SVG(4, 2)) // #nosec G203 -- generated by qr.SVG from our own text
	}
	h.renderSettings(w, r, "", v)
}

// pairRequest is the phone's body.
type pairRequest struct {
	Code       string `json:"code"`
	DeviceName string `json:"deviceName"`
}

// APIPair: POST /api/v1/pair (no key) - exchange a pairing code for a
// device key. Wrong, used and expired codes all fail the same way, and
// an address that keeps failing is locked out for a while.
func (h *Handlers) APIPair(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	ip := auth.ClientIP(r)
	if wait := h.PairLimiter.RetryAfter(ip); wait > 0 {
		w.Header().Set("Retry-After", fmt.Sprintf("%d", int(wait.Seconds())+1))
		writeJSONError(w, http.StatusTooManyRequests, "too many attempts; try again later")
		return
	}
	var in pairRequest
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 64<<10)).Decode(&in); err != nil {
		writeJSONError(w, http.StatusBadRequest, "invalid JSON body")
		return
	}
	code := normalizePairCode(in.Code)
	fail := func() {
		h.PairLimiter.Fail(ip)
		writeJSONError(w, http.StatusBadRequest, "unknown, used or expired pairing code")
	}
	if code == "" {
		fail()
		return
	}
	row, err := h.Queries.GetPairCodeBySHA256(ctx, auth.HashAPIKey(code))
	if err != nil || row.UsedAt != nil || !time.Now().Before(row.ExpiresAt) || row.IsActive == 0 {
		fail()
		return
	}
	if n, err := h.Queries.UsePairCode(ctx, row.ID); err != nil || n == 0 {
		fail()
		return
	}
	name := strings.TrimSpace(in.DeviceName)
	if name == "" {
		name = "Phone"
	}
	if len(name) > 64 {
		name = name[:64]
	}
	full, prefix, sha, err := auth.GenerateAPIKey()
	if err != nil {
		h.serverError(w, fmt.Errorf("generate device key: %w", err))
		return
	}
	if _, err := h.Queries.CreateAPIKey(ctx, models.CreateAPIKeyParams{
		UserID: row.UserID, Name: name, KeyPrefix: prefix, KeySha256: sha, Kind: string(auth.KeyKindDevice), DeviceName: &name,
	}); err != nil {
		h.serverError(w, fmt.Errorf("create device key: %w", err))
		return
	}
	h.PairLimiter.Reset(ip)
	u, err := h.Queries.GetUserByID(ctx, row.UserID)
	if err != nil {
		h.serverError(w, fmt.Errorf("load user: %w", err))
		return
	}
	h.logger().Info("phone paired", "user", u.ID, "device", name)
	writeJSON(w, http.StatusCreated, map[string]any{
		"key":    full,
		"server": h.apiServerInfo(r),
		"user":   apiUserInfo(u),
	})
}

// apiServerInfo is the server as the app shows it in Settings and uses it
// to gate features.
func (h *Handlers) apiServerInfo(r *http.Request) map[string]any {
	return map[string]any{
		"url":      h.pairServerURL(r),
		"version":  h.Version,
		"timezone": h.localTZ().String(),
		"features": map[string]bool{
			"ai":        h.aiPossible(),
			"charts":    h.MarketData != nil,
			"guardrail": h.Guardrail != nil,
			"push":      h.Push.Enabled(),
		},
	}
}

func apiUserInfo(u models.User) map[string]any {
	return map[string]any{"id": u.ID, "username": u.Username, "displayName": derefStr(u.DisplayName), "email": derefStr(u.Email)}
}

// apiUserSettings is the user's switches as the API shows them.
func apiUserSettings(u models.User) map[string]any {
	return map[string]any{"guardrail": u.Guardrail == 1, "autoPlan": u.AutoPlan}
}

// APIMe: GET /api/v1/me - who the key belongs to, the server, the user's
// settings and the key itself.
func (h *Handlers) APIMe(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	u, err := h.rq().GetUserByID(ctx, userID(ctx))
	if err != nil {
		writeJSONError(w, http.StatusInternalServerError, "could not load the user")
		return
	}
	out := map[string]any{
		"user":     apiUserInfo(u),
		"server":   h.apiServerInfo(r),
		"settings": apiUserSettings(u),
		"ai":       h.apiAIState(r),
	}
	if k, ok := auth.APIKeyFrom(ctx); ok {
		out["key"] = map[string]any{"kind": string(k.Kind), "name": k.Name, "createdAt": k.CreatedAt}
	}
	writeJSON(w, http.StatusOK, out)
}

// requireDeviceKey refuses a write that is the trader's to make unless the
// request came with a device key (the paired phone).
func (h *Handlers) requireDeviceKey(w http.ResponseWriter, r *http.Request) bool {
	if auth.IsDeviceKey(r.Context()) {
		return true
	}
	writeJSONError(w, http.StatusForbidden, "this call needs a device key: pair the phone app in Settings")
	return false
}

// APISettingsSave: PUT /api/v1/settings (device key) - change the user's
// switches; present fields change, absent ones are kept.
func (h *Handlers) APISettingsSave(w http.ResponseWriter, r *http.Request) {
	if !h.requireDeviceKey(w, r) {
		return
	}
	ctx := r.Context()
	var in struct {
		Guardrail *bool  `json:"guardrail"`
		AutoPlan  *int64 `json:"autoPlan"`
	}
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 64<<10)).Decode(&in); err != nil {
		writeJSONError(w, http.StatusBadRequest, "invalid JSON body")
		return
	}
	uid := userID(ctx)
	if in.Guardrail != nil {
		on := int64(0)
		if *in.Guardrail {
			on = 1
		}
		if err := h.Queries.SetUserGuardrail(ctx, models.SetUserGuardrailParams{Guardrail: on, ID: uid}); err != nil {
			h.serverError(w, err)
			return
		}
	}
	if in.AutoPlan != nil {
		if *in.AutoPlan < autoPlanOff || *in.AutoPlan > autoPlanSet {
			writeJSONError(w, http.StatusBadRequest, "autoPlan must be 0 (off), 1 (suggest) or 2 (set the plan)")
			return
		}
		if err := h.Queries.SetUserAutoPlan(ctx, models.SetUserAutoPlanParams{AutoPlan: *in.AutoPlan, ID: uid}); err != nil {
			h.serverError(w, err)
			return
		}
		if *in.AutoPlan != autoPlanOff {
			h.LiveData.Bump(uid)
		}
	}
	u, err := h.Queries.GetUserByID(ctx, uid)
	if err != nil {
		h.serverError(w, err)
		return
	}
	h.LiveData.Bump(uid)
	writeJSON(w, http.StatusOK, map[string]any{"settings": apiUserSettings(u)})
}

// deviceKeysOf splits a user's keys into the phones and the agents.
func deviceKeysOf(keys []models.ListAPIKeysForUserRow) (devices, agents []models.ListAPIKeysForUserRow) {
	for _, k := range keys {
		if auth.KeyKind(k.Kind) == auth.KeyKindDevice {
			devices = append(devices, k)
		} else {
			agents = append(agents, k)
		}
	}
	return devices, agents
}

