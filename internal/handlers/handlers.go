// accountFilter holds the parsed multi-select filter shared by /trades,
// /calendar, and /analytics. The `filter` query param accepts multiple values:
//
//	acc:<id>      — include this exact account
//	type:<slug>   — include every account whose `type` matches
//
// The resolved AccountIDs is the OR-union of both kinds. Active is true iff
// the user selected anything, even if the union is empty (then "show none").
// RawValues is the original list of selections, for re-rendering the
// dropdown's selected state. SelectedCount is len(non-empty selections).
type accountFilter struct {
	AccountIDs    []int64
	Active        bool
	RawValues     []string
	Selected      map[string]bool
	SelectedCount int
}

// resolveAccountFilter parses ?filter=acc:N&filter=type:X (multi-valued) into
// a concrete []int64 of accounts to filter by, resolving both forms against
// the USER's accounts: a type slug must not pull in other users' accounts,
// and an explicit id that is not the user's is dropped (the downstream
// predicates would have ANDed it away; resolving it here keeps "show none"
// and the selected count honest).
func (h *Handlers) resolveAccountFilter(r *http.Request) (accountFilter, error) {
	raw := r.URL.Query()["filter"]
	af := accountFilter{RawValues: raw, Selected: map[string]bool{}}
	if len(raw) == 0 {
		return af, nil
	}
	var explicitIDs []int64
	var types []string
	for _, v := range raw {
		if v == "" {
			continue
		}
		af.Selected[v] = true
		af.SelectedCount++
		switch {
		case strings.HasPrefix(v, "acc:"):
			if id, err := strconv.ParseInt(v[4:], 10, 64); err == nil {
				explicitIDs = append(explicitIDs, id)
			}
		case strings.HasPrefix(v, "type:"):
			types = append(types, v[5:])
		}
	}
	if len(explicitIDs) == 0 && len(types) == 0 {
		return af, nil
	}
	af.Active = true
	w := whereUser("user_id = ?", userID(r.Context()))
	var alts []string
	var args []any
	if len(explicitIDs) > 0 {
		ph := strings.Repeat("?,", len(explicitIDs))
		alts = append(alts, "id IN ("+ph[:len(ph)-1]+")")
		for _, id := range explicitIDs {
			args = append(args, id)
		}
	}
	if len(types) > 0 {
		ph := strings.Repeat("?,", len(types))
		alts = append(alts, "type IN ("+ph[:len(ph)-1]+")")
		for _, t := range types {
			args = append(args, t)
		}
	}
	w.and("("+strings.Join(alts, " OR ")+")", args...)
	rows, err := h.rdb().QueryContext(r.Context(), "SELECT id FROM accounts WHERE "+w.sql()+" ORDER BY id", w.args...)
	if err != nil {
		return af, fmt.Errorf("resolve account filter: %w", err)
	}
	defer rows.Close()
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			return af, err
		}
		af.AccountIDs = append(af.AccountIDs, id)
	}
	if err := rows.Err(); err != nil {
		return af, err
	}
	return af, nil
}

// bridgeLegacyAccountID maps the legacy singular ?account_id=N onto the
// multi-select ?filter=acc:N form BEFORE resolveAccountFilter runs, so old
// bookmarks, calendar links and API clients keep working. Returns r itself
// when there is nothing to bridge.
func bridgeLegacyAccountID(r *http.Request) *http.Request {
	legacy := strings.TrimSpace(r.URL.Query().Get("account_id"))
	if legacy == "" {
		return r
	}
	r2 := *r
	r2.URL = cloneURL(r.URL)
	q := r2.URL.Query()
	q.Add("filter", "acc:"+legacy)
	r2.URL.RawQuery = q.Encode()
	return &r2
}

// accountAdmission is the stats account rule as ONE predicate, built from
// the same three sources Calendar/Analytics use: retired accounts never
// count; with an explicit filter only the named accounts count (an empty
// resolved filter admits nothing - "show none", never everything);
// otherwise every account except the excluded_from_stats ones.
type accountAdmission struct {
	active   bool
	allowed  map[int64]bool
	retired  map[int64]bool
	excluded map[int64]bool
}

func newAccountAdmission(af accountFilter, retired, excluded map[int64]bool) accountAdmission {
	a := accountAdmission{active: af.Active, allowed: map[int64]bool{}, retired: retired, excluded: excluded}
	for _, id := range af.AccountIDs {
		a.allowed[id] = true
	}
	return a
}

func (a accountAdmission) admits(accountID int64) bool {
	if a.retired[accountID] {
		return false
	}
	if a.active {
		return a.allowed[accountID]
	}
	return !a.excluded[accountID]
}

// publicBaseURL is the scheme://host to advertise in copy-pasteable URLs:
// the configured external URL when set, else what the request arrived on
// (X-Forwarded-* from the reverse proxy, which an attacker on the same
// network segment could set - hence the preference for configuration).
func (h *Handlers) publicBaseURL(r *http.Request) string {
	if u := strings.TrimRight(strings.TrimSpace(h.ExternalURL), "/"); u != "" {
		return u
	}
	return requestBaseURL(r)
}

