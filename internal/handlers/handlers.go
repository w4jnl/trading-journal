// rdb and rq return the read-only pool, or the writer when none is wired.
func (h *Handlers) rdb() *sql.DB {
	if h.RDB != nil {
		return h.RDB
	}
	return h.DB
}

func (h *Handlers) rq() *models.Queries {
	if h.RQ != nil {
		return h.RQ
	}
	return h.Queries
}

// Handlers groups every HTTP handler with its shared deps. main.go injects
// concrete values; tests can swap any field.
//
// Two database pools: DB/Queries write (and read inside transactions);
// RDB/RQ, reached through rdb()/rq(), serve the read-only handlers. A write
// through rq() fails with "attempt to write a readonly database".
type Handlers struct {
	Templates fs.FS   // embedded template tree; pages live at templates/<name>
	DB        *sql.DB // WRITER pool (one connection): raw SQL for writes and transactions
	ImportSvc *importer.ImportService
	Queries   *models.Queries // sqlc on the writer pool
	// RDB / RQ are the read-only pool (db.OpenReader) that page renders and
	// API reads use through rdb() / rq(), so they never queue behind an
	// import or a sync on the single writer connection. nil (tests) falls
	// back to the writer.
	RDB            *sql.DB
	RQ             *models.Queries
	UploadsDir     string // staging dir for UI uploads — must be on the same filesystem as ImportSvc.ProcessedDir
	AttachmentsDir string // where journal-attached images are stored on disk
	// ExternalURL is cfg.Server.ExternalURL: the public origin the API docs
	// and OpenAPI servers list advertise. "" falls back to the request's
	// forwarded host (publicBaseURL).
	ExternalURL     string
	OIDashboardsDir string // root folder containing daily OI dashboards (dashboard-YYYY-MM-DD.{html,pdf})
	Timezone        *time.Location
	Logger          *slog.Logger
	Version         string // build version shown in the sidebar; set from cmd/server appVersion()

	// CSRF mints + verifies session-bound CSRF tokens. main wires this from
	// cfg.Auth.SessionSecret. Nil = no CSRF (acceptable in proxy mode where
	// the SSO frontend enforces origin checks).
	CSRF *auth.CSRF

	// IbkrGatewayHosts is cfg.IBKR.AllowedGatewayHosts: where non-admin
	// users may point a Client Portal Gateway (see ibkrGatewayHostAllowed).
	IbkrGatewayHosts []string

	// ActAs is the admin "browse as another user" helper. Nil disables
	// the feature (and the /admin/act-as routes return 500-ish).
	ActAs *auth.ActAs

	// MarketData fronts the historical-bar cache for the trade-replay charts.
	// Nil disables charting entirely (the mount points render nothing).
	MarketData *marketdata.CachingSource

	// Prefetch is the background bar-cache warmer. The admin backfill action
	// enqueues missing symbol-days through it. Nil when prefetch is disabled.
	Prefetch *marketdata.Prefetcher
	// Excursions measures MAE/MFE from cached bars; nil when market data
	// is off. The trade sheet fills a closed trade on first view.
	Excursions *excursion.Service

	// MCPInstanceLabel is surfaced by the MCP server_info tool (e.g. "prod" /
	// "dev") so an AI client can tell which instance it is connected to when
	// several trading-journal connectors are configured.
	MCPInstanceLabel string

	// AI is the in-app analysis client (OpenAI-compatible); AIJobs tracks the
	// per-user day-analysis job. Both nil disables server-side AI analysis; wired
	// from cfg.AI when ai.enabled.
	AI     ai.Client
	AIJobs *ai.JobManager

	// AIModel is the configured model id, recorded alongside stored AI output
	// (currently the retained gamma reads) so text generated by a previous
	// model can be told apart later. "" when AI is disabled.
	AIModel string

	// GEX fetches gamma-exposure snapshots for review-time trade annotations.
	// Nil = gex.enabled false; prepare-day then skips annotation entirely.
	GEX *gex.Client

	// TopstepxSync pulls trade history from the TopstepX API. Nil disables the
	// feature (no topstepx.encryption_key configured); the enqueue hooks are
	// nil-receiver-safe so page handlers call them unconditionally.
	TopstepxSync *topstepx.SyncService

	// IbkrSync polls the user-configured IBKR Client Portal Gateways. Nil
	// disables the feature (ibkr.enabled=false); enqueue hooks nil-safe.
	IbkrSync *ibkr.SyncService

	// MWEmailArchiveDir is the MW email capture archive (mw_email.archive_dir)
	// when the listener is enabled; "" otherwise. The accounts page reads the
	// replay journal in it to warn admins about captured fills that could not
	// be attributed to any account.
	MWEmailArchiveDir string

	// LiveData is the per-user data-version notifier behind the pages' live
	// refresh: mutation paths bump it post-commit, GET /data/version serves
	// it, and renderPage stamps the current version into pages that opt in.
	// Nil-safe (Version() on nil returns 0), so tests building bare Handlers
	// keep working; main always wires a real one.
	LiveData *livedata.Notifier

	// OAuth is the built-in authorization server for /mcp (mcp.oauth). The
	// browser-facing /oauth/authorize consent handlers live in this package
	// because they render through the app layout; the protocol logic is in
	// internal/oauth. Nil when the feature is disabled (handlers 404).
	OAuth *oauth.Server

	// templateCache memoizes parsed template sets so renderPage / renderPartial
	// don't re-glob and re-parse the templates fs on every request. Keys
	// distinguish page renders ("page:<name>") from partial renders
	// ("partial:<name>") since the file sets differ.
	templateCache sync.Map

	// journal is the domain service behind every journal write (journalSvc).
	journalOnce sync.Once
	journal     *journal.Service

	// quoteCache memoizes open-position quotes per contract symbol for a few
	// seconds (see quoteCacheTTL) so the dashboard's live refresh does not
	// re-query TopstepX / Yahoo on every render.
	quoteCache sync.Map
}

// renderPage parses base.html + the named page + every _*.html partial in the
// templates dir, and executes the base. Bundling the partials means a page
// can reference any sibling partial via {{template "name" .}} without the
// caller listing it explicitly. The parsed set is cached after first use —
// templates ship in embed.FS so they never change at runtime.
//
// When `data` is a map[string]any (the common case across handlers), the
// caller's r is consulted to inject CurrentUser and CSRFToken so base.html
// can render the auth widget and forms can include the token. Pass nil r
// from non-request callers (none today, but kept open for future tooling).
func (h *Handlers) renderPage(w http.ResponseWriter, r *http.Request, page string, data any) {
	if r != nil {
		if m, ok := data.(map[string]any); ok {
			if _, exists := m["CurrentUser"]; !exists {
				if u := auth.UserFrom(r.Context()); u != nil {
					m["CurrentUser"] = u
				}
			}
			if _, exists := m["CSRFToken"]; !exists && h.CSRF != nil {
				m["CSRFToken"] = h.CSRF.Token(auth.CookieFromRequest(r))
			}
			if _, exists := m["OriginalUser"]; !exists {
				if orig := auth.OriginalUserFrom(r.Context()); orig != nil {
					m["OriginalUser"] = orig
				}
			}
			// The CSP script nonce for this response's inline scripts.
			if _, exists := m["Nonce"]; !exists {
				m["Nonce"] = NonceFrom(r.Context())
			}
			// Always-on open-position badge in the sidebar. Cheap indexed count; the
			// badge is non-critical, so any error just leaves it unset (no badge).
			if _, exists := m["OpenPositionCount"]; !exists {
				if u := auth.UserFrom(r.Context()); u != nil {
					if n, err := h.rq().CountOpenPositions(r.Context(), u.ID); err == nil {
						m["OpenPositionCount"] = n
					}
				}
			}
			// Current data version for the live-refresh marker, keyed on the
			// EFFECTIVE user so an admin acting-as follows the target user's
			// data stream. Pages that don't render the marker just ignore it.
			if _, exists := m["DataVersion"]; !exists {
				if u := auth.UserFrom(r.Context()); u != nil {
					m["DataVersion"] = h.LiveData.Version(u.ID)
				}
			}
		}
	}
	t, err := h.parsedPage(page)
	if err != nil {
		h.serverError(w, fmt.Errorf("parse %s: %w", page, err))
		return
	}
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	if err := t.ExecuteTemplate(w, "base.html", data); err != nil {
		h.logger().Error("render", "page", page, "err", err)
	}
}

// renderPartial renders a single named template — no base wrap. Used for
// HTMX fragment responses. We bundle every `_*.html` partial (same as
// renderPage) so a partial can reference any shared sub-template
// (tag_picker, journal_editor, sketch icons, etc.) without listing them.
func (h *Handlers) renderPartial(w http.ResponseWriter, partial, name string, data any) {
	t, err := h.parsedPartial(partial)
	if err != nil {
		h.serverError(w, fmt.Errorf("parse %s: %w", partial, err))
		return
	}
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	if err := t.ExecuteTemplate(w, name, data); err != nil {
		h.logger().Error("render partial", "name", name, "err", err)
	}
}

// parsedPage returns the cached template set for a page render (base + page
// + every partial). First call for a given page parses; subsequent calls hit
// the cache.
func (h *Handlers) parsedPage(page string) (*template.Template, error) {
	key := "page:" + page
	if v, ok := h.templateCache.Load(key); ok {
		return v.(*template.Template), nil
	}
	partials, err := fs.Glob(h.Templates, "templates/_*.html")
	if err != nil {
		return nil, fmt.Errorf("glob partials: %w", err)
	}
	files := append([]string{"templates/base.html", "templates/" + page}, partials...)
	t, err := template.New("").Funcs(h.funcMap()).ParseFS(h.Templates, files...)
	if err != nil {
		return nil, err
	}
	actual, _ := h.templateCache.LoadOrStore(key, t)
	return actual.(*template.Template), nil
}

// parsedPartial returns the cached template set for a partial render (the
// requested partial + every other partial as siblings).
func (h *Handlers) parsedPartial(partial string) (*template.Template, error) {
	key := "partial:" + partial
	if v, ok := h.templateCache.Load(key); ok {
		return v.(*template.Template), nil
	}
	files := []string{"templates/" + partial}
	siblings, err := fs.Glob(h.Templates, "templates/_*.html")
	if err != nil {
		return nil, fmt.Errorf("glob partials: %w", err)
	}
	for _, sib := range siblings {
		if sib == "templates/"+partial {
			continue
		}
		files = append(files, sib)
	}
	t, err := template.New("").Funcs(h.funcMap()).ParseFS(h.Templates, files...)
	if err != nil {
		return nil, err
	}
	actual, _ := h.templateCache.LoadOrStore(key, t)
	return actual.(*template.Template), nil
}

func (h *Handlers) funcMap() template.FuncMap {
	loc := h.Timezone
	if loc == nil {
		loc = time.UTC
	}
	return template.FuncMap{
		// aiEnabled gates the in-app AI-analysis UI affordances; true only when
		// ai.enabled wired a job manager.
		"aiEnabled": func() bool { return h.AIJobs != nil },
		// gexEnabled gates the Market > Gamma (GEX) nav item + palette entry.
		"gexEnabled": func() bool { return h.GEX != nil },
		// aiAnalyzed reports whether a body already carries the LOCAL AI marker, so the
		// in-app Analyze button hides on an already-analyzed entry (re-running it is a
		// no-op - analyzeEntry skips a marked entry).
		"aiAnalyzed": func(body string) bool { return strings.Contains(body, aiMarkerLocal) },
		// posLabel renders a signed net position (open-positions panel/badge) as
		// "long N" / "short N" with the absolute quantity.
		"posLabel": func(net float64) string {
			if net > 0 {
				return fmt.Sprintf("long %g", net)
			}
			return fmt.Sprintf("short %g", -net)
		},
		// dtlocal formats a UTC time in the trading tz for a datetime-local input, at second
		// precision so an unedited reconcile row round-trips to the same string on save.
		"dtlocal": func(t time.Time) string { return t.In(loc).Format("2006-01-02T15:04:05") },
		// tradeHorizon classifies a closed trade by holding time (Scalp/Intraday/Swing/
		// Long-term); heldFor is the human duration for its tooltip; lower lowercases the
		// horizon into a CSS class suffix.
		"tradeHorizon": tradeHorizon,
		"heldFor":      heldFor,
		"lower":        strings.ToLower,
		"appVersion":   func() string { return h.Version }, // build string in the sidebar footer
		"assetVer":     h.assetQuery,                       // "?v=<build>" on /static URLs; "" for dev builds
		// tradingTZ is the configured trading timezone as an IANA name (e.g.
		// "America/Chicago"), exposed to the client so chart libraries can render
		// their time axes in it instead of UTC. See web/static/js/trade-chart.js.
		"tradingTZ":  func() string { return loc.String() },
		"hasPrefix":  strings.HasPrefix,
		"trimPrefix": strings.TrimPrefix,
		"formatQty":  formatQty, // trailing-zero-free trade quantity
		// lt / ltp render a timestamp as a <time class="lt"> carrying the UTC
		// instant; a small client script (base.html) rewrites the text to the
		// browser's local timezone. The inner text is a UTC fallback for no-JS.
		// fmtKind: "date" | "datetime" | "datetime-sec" | "time".
		"ltime": func(t time.Time, fmtKind string) template.HTML { return localTimeTag(t, fmtKind) },
		"ltimep": func(t *time.Time, fmtKind string) template.HTML {
			if t == nil {
				return ""
			}
			return localTimeTag(*t, fmtKind)
		},
		// markdown renders a markdown string to sanitized HTML. Used by the
		// strategy card (and anywhere a stored markdown doc is shown inline).
		"markdown": func(s string) template.HTML {
			return template.HTML(renderMarkdown(s))
		},
		"derefStr": func(s *string) string {
			if s == nil {
				return ""
			}
			return *s
		},
		// importNote: the import log's message, read for people (import_message.go).
		"importNote": humanizeImportMessage,
		// exitEfficiency: realized over MFE (internal/excursion), nil until
		// the trade is closed and measured or when it never went its way.
		"exitEfficiency": func(direction string, entry float64, exit, mfe *float64) *float64 {
			if exit == nil || mfe == nil {
				return nil
			}
			return excursion.Efficiency(direction, entry, *exit, *mfe)
		},
		// splitLines: a one-item-per-line text as a slice (checklist previews).
		"splitLines": func(s string) []string {
			var out []string
			for _, l := range strings.Split(s, "\n") {
				if l = strings.TrimSpace(l); l != "" {
					out = append(out, l)
				}
			}
			return out
		},
		// Review-label vocabulary for the editors' chips and the view's pills.
		"labelOptions": journal.LabelOptions,
		"labelName":    journal.LabelName,
		"hasStr": func(list []string, v string) bool {
			for _, x := range list {
				if x == v {
					return true
				}
			}
			return false
		},
		// rMultiple formats net P&L over planned risk ("+1.80R"); "" when
		// either is missing so templates can show a dash.
		"rMultiple": func(net, risk *float64) string {
			r := positions.RMultiple(net, risk)
			if r == nil {
				return ""
			}
			return fmt.Sprintf("%+.2fR", *r)
		},
		"deref": func(p *float64) float64 {
			if p == nil {
				return 0
			}
			return *p
		},
		"localtime": func(t time.Time, layout string) string {
			return t.In(loc).Format(layout)
		},
		// pnlClass renders a *float64 with a color span based on sign.
		// Nil values render as a plain em-dash; the position builder writes
		// NULL for trades whose instrument has no tick spec configured yet.
		"pnlClass": func(p *float64) template.HTML {
			if p == nil {
				return template.HTML("—")
			}
			cls := "pnl-pos"
			if *p < 0 {
				cls = "pnl-neg"
			}
			return template.HTML(fmt.Sprintf(`<span class="%s">%.2f</span>`, cls, *p))
		},
		// sparkPolyline scales a []float64 into the `points="x,y x,y …"` string
		// for an inline <svg><polyline></svg> sparkline. Coordinates fit a
		// fixed viewBox (default 60×20). Min-max normalized per series so
		// small absolute moves still render with full vertical range. Empty
		// or single-point series return an empty string (template `{{if}}` can
		// then suppress the SVG cleanly).
		"sparkPolyline": func(ys []float64) string {
			if len(ys) < 2 {
				return ""
			}
			const w, hgt = 60.0, 20.0
			min, max := ys[0], ys[0]
			for _, v := range ys {
				if v < min {
					min = v
				}
				if v > max {
					max = v
				}
			}
			span := max - min
			if span == 0 {
				span = 1 // flat line drawn at mid-height
			}
			step := w / float64(len(ys)-1)
			var b strings.Builder
			for i, v := range ys {
				x := float64(i) * step
				// Invert Y so larger values render higher; 1px padding inset
				// keeps the stroke from clipping at the viewbox edge.
				y := hgt - 1 - ((v-min)/span)*(hgt-2)
				if i > 0 {
					b.WriteByte(' ')
				}
				fmt.Fprintf(&b, "%.1f,%.1f", x, y)
			}
			return b.String()
		},
		// pnlChip renders a tinted-background P&L chip with an explicit +/−
		// sign so winners and losers pop in long lists. Use on the Net P&L
		// column in tables; pnlClass is still right for inline text.
		"pnlChip": func(p *float64) template.HTML {
			if p == nil {
				return template.HTML(`<span class="muted">—</span>`)
			}
			v := *p
			cls := "pnl-chip--soft-pos"
			sign := "+"
			if v < 0 {
				cls = "pnl-chip--soft-neg"
				sign = "−"
				v = -v
			}
			return template.HTML(fmt.Sprintf(`<span class="pnl-chip %s">%s%.2f</span>`, cls, sign, v))
		},
		// dict builds an ad-hoc map from key/value pairs. Useful for passing
		// multi-field data into a sub-template via {{template "x" (dict ...)}}.
		"dict": func(pairs ...any) (map[string]any, error) {
			if len(pairs)%2 != 0 {
				return nil, fmt.Errorf("dict: odd number of arguments")
			}
			out := make(map[string]any, len(pairs)/2)
			for i := 0; i < len(pairs); i += 2 {
				k, ok := pairs[i].(string)
				if !ok {
					return nil, fmt.Errorf("dict: key %d not a string", i/2)
				}
				out[k] = pairs[i+1]
			}
			return out, nil
		},
		// mkRange returns []int64{from, from+1, …, to} for use in {{range}}.
		"mkRange": func(from, to int64) []int64 {
			if to < from {
				return nil
			}
			out := make([]int64, 0, to-from+1)
			for i := from; i <= to; i++ {
				out = append(out, i)
			}
			return out
		},
		"moodEmoji": func(mood int64) string {
			switch mood {
			case 1:
				return "😞"
			case 2:
				return "😕"
			case 3:
				return "😐"
			case 4:
				return "🙂"
			case 5:
				return "😀"
			}
			return ""
		},
		// snippet truncates s to at most n runes, appending "…" if cut.
		// snippet is the one-line preview of a journal body: machine blocks
		// and markdown syntax stripped (preview.go), then cut to n runes.
		"snippet":       previewText,
		"hasAIReview":   hasAIReview,
		"hasGexContext": hasGexContext,
		// pnlSign is the sentiment class for a signed amount: colour follows
		// the SIGN, never the column - a "worst" that is positive is green.
		"pnlSign": func(v float64) string {
			switch {
			case v > 0:
				return "pnl-pos"
			case v < 0:
				return "pnl-neg"
			}
			return ""
		},
		// groupTrades folds copy-trader fan-out (the same decision filled on
		// several accounts within two seconds) into one row per decision for
		// the journal trade tables; see groupLinkedTrades.
		"groupTrades": groupLinkedTrades,
		// cellClass picks a calendar-cell color class based on net P&L magnitude.
		// Threshold is rough: $100 / $-100 separates "regular day" from "big day".
		"cellClass": func(netPnl float64, hasData bool) string {
			if !hasData {
				return ""
			}
			switch {
			case netPnl >= 100:
				return "has-pnl-pos-strong"
			case netPnl > 0:
				return "has-pnl-pos"
			case netPnl <= -100:
				return "has-pnl-neg-strong"
			case netPnl < 0:
				return "has-pnl-neg"
			}
			return ""
		},
		"mul": func(a, b float64) float64 { return a * b },
		"div": func(a, b float64) float64 {
			if b == 0 {
				return 0
			}
			return a / b
		},
		"abs": func(f float64) float64 {
			if f < 0 {
				return -f
			}
			return f
		},
		"i64ToFloat": func(i int64) float64 { return float64(i) },
		"i64ToInt":   func(i int64) int { return int(i) },
		"intToFloat": func(i int) float64 { return float64(i) },
		"negFloat":   func(f float64) float64 { return -f },
		"isInf":      func(f float64) bool { return math.IsInf(f, 0) },
		// barWidth returns 0..100 — the percentage to use as a CSS bar width.
		// Used by the horizontal bar charts (Duration / Win Rate Analysis).
		"barWidth": func(v, max float64) float64 {
			if max <= 0 {
				return 0
			}
			pct := v / max * 100
			if pct < 0 {
				return 0
			}
			if pct > 100 {
				return 100
			}
			return pct
		},
		// humanDuration formats a time.Duration as "X min Y sec" / "X hr Y min"
		// for the dashboard tiles. Compact ASCII, no fractional seconds.
		"humanDuration": func(d time.Duration) string {
			if d <= 0 {
				return "—"
			}
			s := int(d.Seconds())
			if s < 60 {
				return fmt.Sprintf("%d sec", s)
			}
			if s < 3600 {
				return fmt.Sprintf("%d min %d sec", s/60, s%60)
			}
			h := s / 3600
			m := (s % 3600) / 60
			return fmt.Sprintf("%d hr %d min", h, m)
		},
		// journalState maps (hasEntry, tag) onto the journal_icon template's
		// state string: empty / neutral / good / bad. Untagged entries fall
		// back to "neutral" so they still get a distinct color from "empty".
		"journalState": func(has bool, tag string) string {
			if !has {
				return "empty"
			}
			switch tag {
			case "good", "bad", "neutral":
				return tag
			}
			return "neutral"
		},
		// weekCellClass tints a Saturday cell by the *week* net P&L. Threshold
		// is $500 vs $100 for daily — weekly aggregates are naturally bigger.
		"weekCellClass": func(netPnl float64, hasData bool) string {
			if !hasData {
				return ""
			}
			switch {
			case netPnl >= 500:
				return "week-pos-strong"
			case netPnl > 0:
				return "week-pos"
			case netPnl <= -500:
				return "week-neg-strong"
			case netPnl < 0:
				return "week-neg"
			}
			return ""
		},
	}
}

// localTimeTag emits a <time class="lt"> carrying the UTC instant in its
// datetime attribute and a data-fmt shape. The inner text is a UTC fallback;
// the client localizer (base.html) rewrites it to the browser's timezone.
func localTimeTag(t time.Time, fmtKind string) template.HTML {
	u := t.UTC()
	fallback := map[string]string{
		"date":         "2006-01-02",
		"datetime":     "2006-01-02 15:04",
		"datetime-sec": "2006-01-02 15:04:05",
		"time":         "15:04",
	}[fmtKind]
	if fallback == "" {
		fallback = "2006-01-02 15:04"
		fmtKind = "datetime"
	}
	return template.HTML(fmt.Sprintf(
		`<time class="lt" datetime="%s" data-fmt="%s">%s</time>`,
		u.Format(time.RFC3339), fmtKind, u.Format(fallback)))
}

